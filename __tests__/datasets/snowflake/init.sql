CREATE VIEW SALES.CUSTOMER_REVENUE AS
SELECT c."Region Name" AS REGION, SUM(o.AMOUNT) AS REVENUE, COUNT(*) AS ORDER_COUNT
FROM SALES.ORDERS o
JOIN SALES.CUSTOMERS c ON c.ID = o.CUSTOMER_ID
GROUP BY c."Region Name";

